  template <typename Type, uint32_t BASE, std::size_t... I>
  static constexpr auto GetExponentialRoundingTableImpl(std::index_sequence<I...> /*unused*/)
  {
    constexpr auto N = sizeof...(I);
    auto array = std::array<Type, N>{ BASE * Helpers::Math::Constexpr::ipow(Type{ 10 }, N - I - 2)... };
    array[N - 1] = 1;

    return array;
  }

  template <typename Type, uint32_t BASE>
  static constexpr auto GetExponentialRoundingTable()
  {
    const constexpr auto N = std::numeric_limits<Type>::digits10 - 1;
    return GetExponentialRoundingTableImpl<Type, BASE>(std::make_index_sequence<N>());
  }

  template <typename Type, std::size_t... I>
  static constexpr auto GetFowardWritingTableImpl(std::index_sequence<I...> /*unused*/)
  {
    constexpr auto N = sizeof...(I);
    return std::array<Type, N>{ Helpers::Math::Constexpr::ipow(Type{ 10 }, N - I)... };
  }

  template <typename Type>
  static constexpr auto GetFowardWritingTable()
  {
    const constexpr auto N = std::numeric_limits<Type>::digits10 - 1;
    return GetFowardWritingTableImpl<Type>(std::make_index_sequence<N>());
  }

  template <typename Type, std::size_t... I>
  static constexpr auto GetPrecistionTableImpl(std::index_sequence<I...> /*unused*/)
  {
    constexpr auto N = sizeof...(I);
    return std::array<Type, N + 1>{ (10 * Helpers::Math::Constexpr::ipow(Type{ 10 }, I))..., 10 };
  }

  template <typename Type>
  static constexpr auto GetPrecistionTable()
  {
    const constexpr auto N = std::numeric_limits<Type>::digits10 - 1;
    return GetPrecistionTableImpl<Type>(std::make_index_sequence<N>());
  }

  template <typename T, uint32_t BASE, std::size_t... I>
  static constexpr auto GetRoundingTableImpl(std::index_sequence<I...> /*unused*/)
  {
    constexpr auto N = sizeof...(I);
    auto array = std::array<T, N + 1>{ BASE * Helpers::Math::Constexpr::ipow(T{ 10 }, N - I)... };
    array[N] = BASE;
    return array;
  }

  template <typename T, uint32_t BASE>
  static constexpr auto GetRoundingTable()
  {
    constexpr auto N = std::numeric_limits<T>::digits10;
    using IntType = std::remove_cvref_t<decltype(Constants::Tables::Floating<T>::table_3_way::hig)>;
    return GetRoundingTableImpl<IntType, BASE>(std::make_index_sequence<N>());
  }
